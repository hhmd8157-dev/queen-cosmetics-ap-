export const getProducts = (): Product[] => {
  if (typeof window === 'undefined') return initialProducts;
  const stored = localStorage.getItem('queen_cosmetics_products');
  if (!stored) {
    localStorage.setItem('queen_cosmetics_products', JSON.stringify(initialProducts));
    return initialProducts;
  }
  try {
    return JSON.parse(stored);
  } catch {
    return initialProducts;
  }
};

export const saveProducts = (updatedProducts: Product[]): void => {
  if (typeof window !== 'undefined') {
    localStorage.setItem('queen_cosmetics_products', JSON.stringify(updatedProducts));
  }
};

